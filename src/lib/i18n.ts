function format(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (all, key) => (key in vars ? String(vars[key]) : all));
}

function loadLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh';
  } catch {
    return 'zh';
  }
}

let current: Lang = loadLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang) {
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* 隐私模式下写不了也不影响本次使用 */
  }
  applyDocumentLang();
  listeners.forEach((fn) => fn());
}

/** 让系统的拼写检查、字体回退和无障碍工具知道当前语言 */
export function applyDocumentLang() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = current === 'en' ? 'en' : 'zh-CN';
  // 桌面端托盘菜单不在 React 里，单独把语言同步给主进程
  try {
    const bridge = (globalThis as { glimnote?: { setUiLang?: (l: Lang) => Promise<boolean> } }).glimnote;
    void bridge?.setUiLang?.(current);
  } catch {
    /* 网页版没有托盘 */
  }
}

function subscribe(fn: () => void) {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, getLang);
}

export function t(zh: string, vars?: Record<string, string | number>): string {
  const text = current === 'en' ? (EN[zh] ?? zh) : zh;
  return format(text, vars);
}

/** 组件里用：语言切换时自动重渲染 */
export function useT() {
  useLang();
  return t;
}

